#!/usr/bin/env node
'use strict';

/**
 * Restore an M0 logical backup to a verified, separate Supabase staging project.
 * The script refuses to target the production ref and is dry-run by default.
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');

function parseArgs(argv) {
  const out = {};
  for (const raw of argv.slice(2)) {
    if (!raw.startsWith('--')) continue;
    const pos = raw.indexOf('=');
    if (pos === -1) out[raw.slice(2)] = true;
    else out[raw.slice(2, pos)] = raw.slice(pos + 1);
  }
  return out;
}

function safeError(value) {
  return String(value || '')
    .replace(/sbp_[A-Za-z0-9_-]+/g, '[REDACTED_TOKEN]')
    .replace(/(password|token|secret)=([^\s&]+)/gi, '$1=[REDACTED]')
    .slice(-4000);
}

function quoteIdent(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function quoteLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function dollarJson(value) {
  const json = JSON.stringify(value);
  const tag = `m0${crypto.createHash('sha256').update(json).digest('hex').slice(0, 12)}`;
  return `$${tag}$${json}$${tag}$::jsonb`;
}

function commandJson(node, cliJs, cliArgs) {
  const result = spawnSync(node, [cliJs, ...cliArgs], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: '1' },
  });
  if (result.status !== 0) throw new Error(safeError(result.stderr || result.stdout));
  const stdout = String(result.stdout || '');
  const arrayStart = stdout.indexOf('[');
  const objectStart = stdout.indexOf('{');
  const start = arrayStart >= 0 && (objectStart < 0 || arrayStart < objectStart) ? arrayStart : objectStart;
  if (start < 0) throw new Error(`Command returned no JSON: ${safeError(stdout)}`);
  return JSON.parse(stdout.slice(start));
}

function query(node, cliJs, projectRef, sql) {
  const payload = commandJson(node, cliJs, [
    'db', 'query', '--linked', '--project-ref', projectRef, '--output', 'json', sql,
  ]);
  if (!Array.isArray(payload.rows)) throw new Error('Query response has no rows array.');
  return payload.rows;
}

function parseAcl(acl) {
  if (!acl || acl === '{}') return [];
  return String(acl).slice(1, -1).split(',').map((entry) => {
    const eq = entry.indexOf('=');
    if (eq < 0) return null;
    const grantee = entry.slice(0, eq) || 'PUBLIC';
    const privileges = entry.slice(eq + 1).split('/')[0] || '';
    return { grantee, execute: privileges.includes('X') };
  }).filter(Boolean);
}

function parsePgArray(value) {
  if (Array.isArray(value)) return value;
  const text = String(value || '').trim();
  if (!text.startsWith('{') || !text.endsWith('}')) return [];
  return text.slice(1, -1).split(',').map((item) => item.replace(/^"|"$/g, '')).filter(Boolean);
}

function makeCreateTable(table, columns) {
  const definitions = columns.map((column) => {
    let definition = `${quoteIdent(column.column_name)} ${column.data_type}`;
    if (column.identity_kind === 'a') definition += ' GENERATED ALWAYS AS IDENTITY';
    else if (column.identity_kind === 'd') definition += ' GENERATED BY DEFAULT AS IDENTITY';
    else if (column.generated_kind === 's') {
      definition += ` GENERATED ALWAYS AS (${column.default_expression}) STORED`;
    } else if (column.default_expression) definition += ` DEFAULT ${column.default_expression}`;
    if (column.not_null) definition += ' NOT NULL';
    return definition;
  });
  return `CREATE TABLE IF NOT EXISTS public.${quoteIdent(table)} (\n  ${definitions.join(',\n  ')}\n);`;
}

function makeInsert(table, columns, rows) {
  if (!rows.length) return [];
  const columnNames = columns.map((column) => quoteIdent(column.column_name));
  const hasIdentity = columns.some((column) => column.identity_kind);
  const chunks = [];
  for (let i = 0; i < rows.length; i += 100) {
    const chunk = rows.slice(i, i + 100);
    chunks.push(
      `INSERT INTO public.${quoteIdent(table)} (${columnNames.join(', ')})${hasIdentity ? ' OVERRIDING SYSTEM VALUE' : ''}\n` +
      `SELECT ${columnNames.join(', ')} FROM jsonb_populate_recordset(NULL::public.${quoteIdent(table)}, ${dollarJson(chunk)});`
    );
  }
  return chunks;
}

function writePhase(backupDir, name, statements) {
  const file = path.join(backupDir, name);
  const body = ['BEGIN;', "SET LOCAL statement_timeout = '0';", "SET LOCAL lock_timeout = '10s';", ...statements.filter(Boolean), 'COMMIT;'].join('\n\n') + '\n';
  fs.writeFileSync(file, body, { mode: 0o600 });
  fs.chmodSync(file, 0o600);
  return file;
}

function applyPhase(cliJs, targetRef, file) {
  const result = spawnSync(process.execPath, [
    cliJs,
    'db', 'query', '--linked', '--project-ref', targetRef,
    '--file', file,
    '--output', 'json',
  ], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: '1' },
  });
  if (result.status !== 0) throw new Error(safeError(result.stderr || result.stdout));
}

const args = parseArgs(process.argv);
const productionRef = String(args['production-ref'] || '').trim();
const targetRef = String(args['target-ref'] || '').trim();
const expectedTargetName = String(args['expected-target-name'] || 'MAGNET OS STAGING');
const backupDir = path.resolve(String(args['backup-dir'] || ''));
const cliJs = path.resolve(String(args['cli-js'] || ''));
const apply = Boolean(args.apply);
const resumeFinalize = Boolean(args['resume-finalize']);

if (!/^[a-z]{20}$/.test(productionRef) || !/^[a-z]{20}$/.test(targetRef)) {
  console.error('ERROR: production and target refs must be explicit 20-character project refs.');
  process.exit(2);
}
if (targetRef === productionRef) {
  console.error('REFUSED: staging restore target equals the production project ref.');
  process.exit(2);
}
if (!args['backup-dir'] || !backupDir.includes(`${path.sep}backups${path.sep}`)) {
  console.error('ERROR: --backup-dir must point to a directory under backups/.');
  process.exit(2);
}
if (!fs.existsSync(cliJs)) {
  console.error('ERROR: Supabase CLI entrypoint not found.');
  process.exit(2);
}

const backupFile = path.join(backupDir, 'logical-backup.json');
const backup = JSON.parse(fs.readFileSync(backupFile, 'utf8'));
if (backup.format !== 'magnet-os-m0-logical-backup' || backup.sourceProjectRef !== productionRef) {
  console.error('REFUSED: backup identity/source project does not match the declared production ref.');
  process.exit(2);
}

const projects = commandJson(process.execPath, cliJs, ['projects', 'list', '--output', 'json']);
const target = projects.find((project) => project.ref === targetRef);
if (!target || target.name !== expectedTargetName || target.status !== 'ACTIVE_HEALTHY') {
  console.error('REFUSED: target project is missing, unhealthy, or does not have the expected staging name.');
  process.exit(2);
}

const existing = query(process.execPath, cliJs, targetRef, `
  select count(*)::bigint as user_relations
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind in ('r','p','v','m')
`)[0];
if (Number(existing.user_relations) !== 0 && !resumeFinalize) {
  console.error('REFUSED: staging public schema is not empty; no destructive cleanup will be attempted.');
  process.exit(2);
}
if (Number(existing.user_relations) === 0 && resumeFinalize) {
  console.error('REFUSED: --resume-finalize requires the already-restored staging tables.');
  process.exit(2);
}

if (resumeFinalize) {
  const expectedCounts = Object.fromEntries(Object.entries(backup.publicData).map(([name, rows]) => [name, rows.length]));
  const countSql = Object.keys(expectedCounts).sort().map((table) =>
    `select ${quoteLiteral(table)} as table_name,count(*)::bigint as row_count from public.${quoteIdent(table)}`
  ).join(' union all ');
  const actualCounts = Object.fromEntries(query(process.execPath, cliJs, targetRef, countSql).map((row) => [row.table_name, Number(row.row_count)]));
  const mismatch = Object.keys(expectedCounts).filter((table) => actualCounts[table] !== expectedCounts[table]);
  const placeholderCount = Number(query(process.execPath, cliJs, targetRef, `
    select count(*)::bigint as row_count from auth.users
    where raw_app_meta_data @> '{"staging_placeholder":true}'::jsonb
  `)[0].row_count);
  if (mismatch.length || placeholderCount !== backup.authInventory.users.length) {
    console.error(`REFUSED: staging restore data does not match the backup; mismatched tables: ${mismatch.join(', ') || 'none'}.`);
    process.exit(2);
  }
}

const schema = backup.schemaInventory;
const baseStatements = [
  'CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;',
  'CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;',
];

for (const type of schema.enums) {
  const labels = type.labels.map(quoteLiteral).join(', ');
  baseStatements.push(`DO $$ BEGIN CREATE TYPE public.${quoteIdent(type.type_name)} AS ENUM (${labels}); EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
}

const columnsByTable = new Map();
for (const column of schema.columns) {
  if (!columnsByTable.has(column.table_name)) columnsByTable.set(column.table_name, []);
  columnsByTable.get(column.table_name).push(column);
}

const serialColumns = schema.columns.map((column) => {
  const match = String(column.default_expression || '').match(/^nextval\('([^']+)'::regclass\)$/);
  if (!match) return null;
  const sequenceName = match[1].includes('.') ? match[1].split('.').pop() : match[1];
  return { ...column, sequenceName };
}).filter(Boolean);
for (const serial of serialColumns) {
  baseStatements.push(`CREATE SEQUENCE IF NOT EXISTS public.${quoteIdent(serial.sequenceName)};`);
}
for (const [table, columns] of [...columnsByTable.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  baseStatements.push(makeCreateTable(table, columns));
}
for (const serial of serialColumns) {
  baseStatements.push(`ALTER SEQUENCE public.${quoteIdent(serial.sequenceName)} OWNED BY public.${quoteIdent(serial.table_name)}.${quoteIdent(serial.column_name)};`);
}

const constraintNames = new Set(schema.constraints.map((constraint) => constraint.constraint_name));
const nonForeignConstraints = schema.constraints
  .filter((constraint) => constraint.constraint_type !== 'f')
  .sort((a, b) => a.table_name.localeCompare(b.table_name) || a.constraint_name.localeCompare(b.constraint_name));
const foreignConstraints = schema.constraints
  .filter((constraint) => constraint.constraint_type === 'f')
  .sort((a, b) => a.table_name.localeCompare(b.table_name) || a.constraint_name.localeCompare(b.constraint_name));

for (const constraint of nonForeignConstraints) {
  baseStatements.push(`ALTER TABLE public.${quoteIdent(constraint.table_name)} ADD CONSTRAINT ${quoteIdent(constraint.constraint_name)} ${constraint.definition};`);
}
for (const index of schema.indexes) {
  if (constraintNames.has(index.index_name)) continue;
  const ddl = index.definition
    .replace(/^CREATE UNIQUE INDEX /i, 'CREATE UNIQUE INDEX IF NOT EXISTS ')
    .replace(/^CREATE INDEX /i, 'CREATE INDEX IF NOT EXISTS ');
  baseStatements.push(`${ddl};`);
}

const authStatements = [];

// Staging Auth remains a separate service. These disabled placeholder users only
// preserve public.profile foreign keys; no password hashes, identities or live
// sessions are copied from Production Auth.
for (const user of backup.authInventory.users) {
  const syntheticEmail = `staging+${user.id}@example.invalid`;
  authStatements.push(`
    INSERT INTO auth.users
      (instance_id,id,aud,role,email,encrypted_password,email_confirmed_at,created_at,updated_at,
       raw_app_meta_data,raw_user_meta_data,is_super_admin,is_anonymous)
    VALUES
      (coalesce((select id from auth.instances limit 1),'00000000-0000-0000-0000-000000000000'::uuid),
       ${quoteLiteral(user.id)}::uuid,${quoteLiteral(user.aud || 'authenticated')},${quoteLiteral(user.role || 'authenticated')},
       ${quoteLiteral(syntheticEmail)},NULL,NULL,coalesce(${quoteLiteral(user.created_at)}::timestamptz,now()),
       coalesce(${quoteLiteral(user.updated_at)}::timestamptz,now()),
       '{"provider":"email","providers":["email"],"staging_placeholder":true}'::jsonb,'{}'::jsonb,false,false)
    ON CONFLICT (id) DO NOTHING;
  `);
}

const dataPhases = [];
for (const [table, rows] of Object.entries(backup.publicData).sort(([a], [b]) => a.localeCompare(b))) {
  const inserts = makeInsert(table, columnsByTable.get(table) || [], rows);
  inserts.forEach((sql, index) => dataPhases.push({ table, index: index + 1, sql }));
}

const finalizeStatements = [];
for (const fn of schema.functions) finalizeStatements.push(fn.definition.trim().replace(/;?$/, ';'));

for (const view of schema.views) {
  if (view.view_kind === 'v') {
    finalizeStatements.push(`CREATE OR REPLACE VIEW public.${quoteIdent(view.view_name)} AS\n${view.definition};`);
  }
}

for (const constraint of foreignConstraints) {
  finalizeStatements.push(`ALTER TABLE public.${quoteIdent(constraint.table_name)} ADD CONSTRAINT ${quoteIdent(constraint.constraint_name)} ${constraint.definition};`);
}

for (const trigger of schema.triggers) finalizeStatements.push(`${trigger.definition};`);

for (const relation of schema.relations) {
  if (relation.schema_name !== 'public' || !['r', 'p'].includes(relation.relation_kind)) continue;
  if (relation.rls_enabled) finalizeStatements.push(`ALTER TABLE public.${quoteIdent(relation.relation_name)} ENABLE ROW LEVEL SECURITY;`);
  if (relation.force_rls) finalizeStatements.push(`ALTER TABLE public.${quoteIdent(relation.relation_name)} FORCE ROW LEVEL SECURITY;`);
}

for (const policy of schema.policies.filter((item) => item.schemaname === 'public')) {
  const roles = parsePgArray(policy.roles).map(quoteIdent).join(', ');
  let sql = `CREATE POLICY ${quoteIdent(policy.policyname)} ON public.${quoteIdent(policy.tablename)} AS ${policy.permissive} FOR ${policy.cmd} TO ${roles}`;
  if (policy.qual) sql += ` USING (${policy.qual})`;
  if (policy.with_check) sql += ` WITH CHECK (${policy.with_check})`;
  finalizeStatements.push(`${sql};`);
}

for (const grant of schema.grants) {
  const grantee = grant.grantee === 'PUBLIC' ? 'PUBLIC' : quoteIdent(grant.grantee);
  finalizeStatements.push(`GRANT ${grant.privilege_type} ON TABLE public.${quoteIdent(grant.table_name)} TO ${grantee}${grant.is_grantable === 'YES' ? ' WITH GRANT OPTION' : ''};`);
}

for (const fn of schema.functions) {
  const signature = `public.${quoteIdent(fn.function_name)}(${fn.identity_arguments || ''})`;
  finalizeStatements.push(`REVOKE ALL ON FUNCTION ${signature} FROM PUBLIC, anon, authenticated, service_role;`);
  for (const acl of parseAcl(fn.acl)) {
    if (!acl.execute || acl.grantee === 'postgres') continue;
    const grantee = acl.grantee === 'PUBLIC' ? 'PUBLIC' : quoteIdent(acl.grantee);
    finalizeStatements.push(`GRANT EXECUTE ON FUNCTION ${signature} TO ${grantee};`);
  }
}

for (const [table, columns] of columnsByTable.entries()) {
  const identity = columns.find((column) => column.identity_kind);
  if (!identity || !(backup.publicData[table] || []).length) continue;
  finalizeStatements.push(`SELECT setval(pg_get_serial_sequence('public.${table}', '${identity.column_name}'), coalesce((select max(${quoteIdent(identity.column_name)}) from public.${quoteIdent(table)}),1), true);`);
}
for (const serial of serialColumns) {
  if (!(backup.publicData[serial.table_name] || []).length) continue;
  finalizeStatements.push(`SELECT setval('public.${serial.sequenceName}'::regclass, coalesce((select max(${quoteIdent(serial.column_name)}) from public.${quoteIdent(serial.table_name)}),1), true);`);
}

if (backup.migrationState.length) {
  finalizeStatements.push(`CREATE SCHEMA IF NOT EXISTS supabase_migrations;`);
  finalizeStatements.push(`
    CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
      version text PRIMARY KEY,
      statements text[],
      name text,
      created_by text,
      idempotency_key text,
      rollback text[]
    );
  `);
  finalizeStatements.push(`
    INSERT INTO supabase_migrations.schema_migrations
    SELECT * FROM jsonb_populate_recordset(NULL::supabase_migrations.schema_migrations, ${dollarJson(backup.migrationState)});
  `);
}

const phaseFiles = [];
phaseFiles.push(writePhase(backupDir, 'staging-restore-00-schema.sql', baseStatements));
phaseFiles.push(writePhase(backupDir, 'staging-restore-01-auth-placeholders.sql', authStatements));
for (const phase of dataPhases) {
  const safeTable = phase.table.replace(/[^A-Za-z0-9_]/g, '_');
  phaseFiles.push(writePhase(backupDir, `staging-restore-10-data-${safeTable}-${String(phase.index).padStart(3, '0')}.sql`, [phase.sql]));
}
phaseFiles.push(writePhase(backupDir, 'staging-restore-90-finalize.sql', finalizeStatements));
const filesToApply = resumeFinalize ? [phaseFiles[phaseFiles.length - 1]] : phaseFiles;

const restoreFile = path.join(backupDir, 'staging-restore.sql');
const combined = phaseFiles.map((file) => `-- ${path.basename(file)}\n${fs.readFileSync(file, 'utf8')}`).join('\n');
fs.writeFileSync(restoreFile, combined, { mode: 0o600 });
fs.chmodSync(restoreFile, 0o600);

console.log(`Verified target: ${target.name} (${target.ref})`);
console.log(`Restore source: ${backupFile}`);
console.log(`Planned public tables: ${Object.keys(backup.publicData).length}`);
console.log(`Planned public rows: ${Object.values(backup.publicData).reduce((sum, rows) => sum + rows.length, 0)}`);
console.log(`Planned records rows: ${(backup.publicData.records || []).length}`);
console.log(`Planned Auth placeholders: ${backup.authInventory.users.length}`);
console.log(`Planned restore phases: ${filesToApply.length}${resumeFinalize ? ' (finalize resume only)' : ''}`);
console.log(`Restore SQL: ${restoreFile}`);

if (!apply) {
  console.log('DRY-RUN complete — staging was not changed.');
  process.exit(0);
}

for (let index = 0; index < filesToApply.length; index += 1) {
  const file = filesToApply[index];
  try {
    applyPhase(cliJs, targetRef, file);
  } catch (error) {
    console.error(`RESTORE FAILED in staging phase ${index + 1}/${filesToApply.length} (${path.basename(file)}). Production was not touched. The failing phase rolled back: ${safeError(error.message)}`);
    process.exit(1);
  }
  if ((index + 1) % 10 === 0 || index === filesToApply.length - 1) {
    console.log(`Applied staging phase ${index + 1}/${filesToApply.length}`);
  }
}
console.log('RESTORE APPLIED — all staging phases committed successfully.');
